import type { Campaign, Task } from '../../shared/types';

function mission(input: Omit<Task, 'objectives' | 'resources'> & {
  objectives: [string, string, string]; resources: [string, string][];
}): Task {
  return { ...input,
    objectives: input.objectives.map((text, index) => ({ id: `${input.id}-o${index + 1}`, text })),
    resources: input.resources.map(([title, path]) => ({ title, url: `https://docs.python.org/zh-cn/3/${path}` })),
  };
}

